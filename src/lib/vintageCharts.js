export function getVintageChart(region, type) {
  if (!region) return null
  const r = region.trim()

  if (r.includes('Burgundy') || r.includes('Bourgogne')) {
    if (type === 'White') return VINTAGE_CHARTS['Burgundy Blanc']
    if (r.includes('Nuits') || r.includes('Gevrey') || r.includes('Vosne') || r.includes('Chambolle') || r.includes('Morey') || r.includes('Flagey')) return VINTAGE_CHARTS['Burgundy Côte de Nuits']
    if (r.includes('Beaune') || r.includes('Volnay') || r.includes('Pommard') || r.includes('Corton') || r.includes('Meursault') || r.includes('Puligny') || r.includes('Chassagne')) return VINTAGE_CHARTS['Burgundy Côte de Beaune']
    return VINTAGE_CHARTS['Burgundy Côte de Nuits']
  }
  if (r.includes('Gevrey') || r.includes('Vosne') || r.includes('Chambolle') || r.includes('Nuits-Saint-Georges')) return VINTAGE_CHARTS['Burgundy Côte de Nuits']
  if (r.includes('Volnay') || r.includes('Pommard') || r.includes('Beaune') || r.includes('Meursault') || r.includes('Puligny') || r.includes('Chassagne')) return VINTAGE_CHARTS['Burgundy Côte de Beaune']
  if (r.includes('Margaret River')) return VINTAGE_CHARTS['Margaret River']
  if (r.includes('Barossa')) return VINTAGE_CHARTS['Barossa Valley']
  if (r.includes('Rhône') || r.includes('Rhone')) return VINTAGE_CHARTS['Northern Rhône']
  if (r.includes('Champagne')) return VINTAGE_CHARTS['Champagne']
  if (r.includes('Barolo') || r.includes('Barbaresco') || r.includes('Piedmont') || r.includes('Langhe')) return VINTAGE_CHARTS['Barolo']
  if (r.includes('Pomerol') || r.includes('Saint-Émilion') || r.includes('St-Emilion') || r.includes('St Emilion')) return VINTAGE_CHARTS['Bordeaux Right Bank']
  if (r.includes('Bordeaux') || r.includes('Pauillac') || r.includes('Margaux') || r.includes('Saint-Julien') || r.includes('Médoc') || r.includes('Pessac')) return VINTAGE_CHARTS['Bordeaux Left Bank']
  return null
}
