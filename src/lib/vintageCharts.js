export const REGION_MAP = {
  'Burgundy': ['Burgundy Rouge', 'Burgundy Blanc'],
  'Margaret River': ['Margaret River'],
  'Barossa Valley': ['Barossa Valley'],
  'Northern Rhône': ['Northern Rhône'],
  'Champagne': ['Champagne'],
  'Barolo': ['Barolo'],
  'Barbaresco': ['Barolo'],
  'Bordeaux': ['Bordeaux'],
}

export function getVintageChart(region, type) {
  if (!region) return null
  const r = region.trim()
  if (r.includes('Burgundy') || r.includes('Bourgogne')) {
    return type === 'White' ? VINTAGE_CHARTS['Burgundy Blanc'] : VINTAGE_CHARTS['Burgundy Rouge']
  }
  if (r.includes('Margaret River')) return VINTAGE_CHARTS['Margaret River']
  if (r.includes('Barossa')) return VINTAGE_CHARTS['Barossa Valley']
  if (r.includes('Rhône') || r.includes('Rhone')) return VINTAGE_CHARTS['Northern Rhône']
  if (r.includes('Champagne')) return VINTAGE_CHARTS['Champagne']
  if (r.includes('Barolo') || r.includes('Barbaresco') || r.includes('Piedmont') || r.includes('Langhe')) return VINTAGE_CHARTS['Barolo']
  if (r.includes('Bordeaux') || r.includes('Pauillac') || r.includes('Margaux') || r.includes('Saint-Julien') || r.includes('Pomerol') || r.includes('Saint-Émilion')) return VINTAGE_CHARTS['Bordeaux']
  return null
}
